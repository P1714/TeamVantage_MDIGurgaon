"""Generate docs/data_dictionary.md: every input field, its code, unit, coverage and provenance (computed from the files)."""
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "data"
pat = pd.read_csv(D / "ehr" / "patients.csv")
obs = pd.read_csv(D / "ehr" / "observations.csv")
cond = pd.read_csv(D / "ehr" / "conditions.csv")
med = pd.read_csv(D / "ehr" / "medications.csv")
wear = pd.read_parquet(D / "wearables_5min.parquet")
meals = pd.read_csv(D / "meal_log.csv")
card = json.loads((ROOT / "models" / "model_card.json").read_text())
n = pat.Id.nunique()

o = obs.groupby(["KEY", "CODE", "UNITS"]).agg(patients=("PATIENT", "nunique"), values=("VALUE", "size")).reset_index()
o_rows = "\n".join(f"| `{r.KEY}` | {r.CODE} | {r.UNITS} | {r.patients / n * 100:.0f}% | {r.values / r.patients:.1f} |" for r in o.itertuples())
wcols = {"cgm_mgdl": ("mg/dL", "CGM interstitial glucose, every 5 min"), "hr_bpm": ("beats/min", "heart rate"),
         "hrv_rmssd_ms": ("ms", "heart-rate variability (RMSSD)"), "steps": ("steps / 5 min", "step count"),
         "sleep_stage": ("0 awake, 1 light, 2 deep, 3 REM", "sleep stage")}
w_rows = "\n".join(f"| `{c}` | {u} | {d} | {wear[c].isna().mean() * 100:.1f}% |" for c, (u, d) in wcols.items())

feat_note = ""
fp = D / "processed" / "features.parquet"
if fp.exists():
    f = pd.read_parquet(fp, columns=card["features"])
    miss = f.isna().mean().sort_values(ascending=False)
    top = miss[miss > 0].head(12)
    feat_note = ("| Feature | Missing in decision rows |\n|---|---|\n" +
                 "\n".join(f"| `{k}` | {v * 100:.1f}% |" for k, v in top.items()) +
                 f"\n\n{int((miss == 0).sum())} of {len(miss)} features are never missing. LightGBM handles missing values natively "
                 "(learned default direction); no imputation is applied. Features that need history (yesterday, personal baselines) are "
                 "missing until that history exists, which is why the twin is fitted on week 1 and evaluation starts on day 8.")

md = f"""# Data dictionary

*Generated by `scripts/build_data_dictionary.py` from the files in `data/`. All data are synthetic (India-context simulation) except `data/real/`.*

## Provenance

| Dataset | Source | Type | Licence | Used for |
|---|---|---|---|---|
| `data/ehr/*.csv` | `madhutwin/simulate.py` + `ehr.py` (Synthea CSV schema) | Synthetic | MIT (this repo) | Twin prior, EHR features |
| `data/wearables_5min.parquet` | `madhutwin/simulate.py` (physiology + sensor model) | Synthetic, replayed | MIT | Twin state, features, labels |
| `data/meal_log.csv` | `madhutwin/simulate.py` (incomplete, under-estimated logging) | Synthetic | MIT | Twin inputs, habits |
| `data/truth/` | simulator hidden parameters | Synthetic ground truth | MIT | Evaluation only, never a model input |
| `data/real/` | Hall et al. 2018 (PLOS Biology); Colas et al. 2019 (PLOS ONE), via GlucoBench | Real, de-identified | CC-BY 4.0 / CC-BY | Separate retrospective experiment; see `data/real/README.md` for transformations and the derived diagnosis rule |

## Static EHR ({n} synthetic patients)

**Tables.**
- `patients.csv`: Id, birth date, sex, city, region, urban/rural.
- `conditions.csv`: SNOMED CT codes ({cond.CODE.nunique()} distinct).
- `medications.csv`: RxNorm codes; {med.MED_CLASS.nunique()} drug classes: {", ".join(sorted(med.MED_CLASS.unique()))}.
- `observations.csv`: LOINC-coded labs and vitals, listed below.

| Key | LOINC code | Unit | Patients with a value | Values per patient |
|---|---|---|---|---|
{o_rows}

Genotype rows (`tcf7l2`, `kcnj11`, `fto`, `prs_t2d`) stay in the record for context. They are **not** inputs to the risk model, because they added no predictive value.

## Dynamic streams (5-minute grid, 21 days per patient)

| Column | Unit | Meaning | Missing |
|---|---|---|---|
{w_rows}

Missing CGM comes from sensor warm-up, dropouts and gaps. Missing HR/HRV comes from the watch being off-wrist or charging. The alert policy suppresses alerts when fewer than 9 of the last 12 CGM readings are present.

**Meal log** (`meal_log.csv`): {len(meals):,} logged meals with columns patient_id, t (minutes), timestamp, food, carbs_g (as logged), gi. About half of the meals actually eaten are logged, and logged carbs are noisy and under-estimated.

## Model inputs ({len(card['features'])} features)

{feat_note}
"""
(ROOT / "docs" / "data_dictionary.md").write_text(md)
print("wrote docs/data_dictionary.md")
